#!/usr/bin/env python3
"""Writes mcp/fetch/tools.vu: the reference fetch server's tool and prompt lists, exactly as its
tools/list and prompts/list return them, as Vu text constants.
  tools/mcp_fetch_tools.py PYTHON     (a Python that has mcp-server-fetch, as tests/run_mcp_fetch.sh sets up)"""
import json, os, subprocess, sys
p = subprocess.Popen([sys.argv[1], "-m", "mcp_server_fetch"], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
msgs = [{"jsonrpc": "2.0", "id": 0, "method": "initialize", "params": {"protocolVersion": "2025-11-25", "capabilities": {}, "clientInfo": {"name": "gen", "version": "1"}}},
        {"jsonrpc": "2.0", "method": "notifications/initialized"},
        {"jsonrpc": "2.0", "id": 1, "method": "tools/list"}, {"jsonrpc": "2.0", "id": 2, "method": "prompts/list"}]
for m in msgs: p.stdin.write((json.dumps(m) + "\n").encode())
p.stdin.flush()
init = json.loads(p.stdout.readline())["result"]
tools = json.loads(p.stdout.readline())["result"]["tools"]
prompts = json.loads(p.stdout.readline())["result"]["prompts"]
p.stdin.close(); p.wait()
def vu(v): return json.dumps(v, separators=(",", ":"), ensure_ascii=False).replace("\\", "\\\\").replace("{", "{{").replace("}", "}}")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mcp", "fetch", "tools.vu")
with open(out, "w") as f:
    f.write("# The tool and the prompt, exactly as the reference server (mcp-server-fetch %s) lists them.\n"
            "# Generated by tools/mcp_fetch_tools.py.\n" % init["serverInfo"]["version"])
    f.write('const VERSION = "%s"\n' % init["serverInfo"]["version"])
    f.write('const TOOLS = """\n%s\n"""\n' % vu(tools))
    f.write('const PROMPTS = """\n%s\n"""\n' % vu(prompts))
print("%d tools, %d prompts -> %s" % (len(tools), len(prompts), out))
