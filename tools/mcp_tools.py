#!/usr/bin/env python3
"""Writes mcp/filesystem/tools.vu: the tool list of the reference MCP filesystem server, exactly as its
tools/list returns it, as a Vu text constant.
  tools/mcp_tools.py REF_SERVER_JS      (@modelcontextprotocol/server-filesystem's dist/index.js)"""
import json, os, subprocess, sys, tempfile
ref = sys.argv[1]
d = tempfile.mkdtemp()
p = subprocess.Popen(["node", ref, d], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
init = {"jsonrpc": "2.0", "id": 0, "method": "initialize", "params": {"protocolVersion": "2025-11-25", "capabilities": {}, "clientInfo": {"name": "gen", "version": "1"}}}
for m in [init, {"jsonrpc": "2.0", "method": "notifications/initialized"}, {"jsonrpc": "2.0", "id": 1, "method": "tools/list"}]:
    p.stdin.write((json.dumps(m) + "\n").encode())
p.stdin.flush()
p.stdout.readline()
tools = json.loads(p.stdout.readline())["result"]["tools"]
p.stdin.close(); p.wait()
txt = json.dumps(tools, separators=(",", ":"), ensure_ascii=False)
vu = txt.replace("\\", "\\\\").replace("{", "{{").replace("}", "}}")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mcp", "filesystem", "tools.vu")
with open(out, "w") as f:
    f.write("# The tools, exactly as the reference server (@modelcontextprotocol/server-filesystem 2.0.1) lists them:\n"
            "# names, descriptions, input and output schemas and annotations. Generated by tools/mcp_tools.py.\n"
            'const TOOLS = """\n  %s\n  """\n' % vu)
print("%d tools -> %s" % (len(tools), out))
