"""Generates compiler/rt/norm.c: the tables behind s.normalize("NFC" / "NFD" / "NFKC" / "NFKD"), from
Python's unicodedata, so Vu normalizes exactly as Python does: each character's canonical combining
class, its full canonical and compatibility decompositions (Hangul syllables are done by formula), and
the pairs that compose (canonical decompositions of two characters that NFC puts back together).
Run from the repository root:  python3 tools/gen_norm.py   (the result is checked in)."""
import sys
import unicodedata as u

def is_hangul(cp):
    return 0xAC00 <= cp <= 0xD7A3

ccc, nfd, nfkd, comp = [], [], [], []
for cp in range(0, 0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    k = u.combining(c)
    if k:
        ccc.append((cp, k))
    if is_hangul(cp):
        continue
    d = u.normalize('NFD', c)
    if d != c:
        nfd.append((cp, [ord(x) for x in d]))
    kd = u.normalize('NFKD', c)
    if kd != c:
        nfkd.append((cp, [ord(x) for x in kd]))
    raw = u.decomposition(c)
    if raw and not raw.startswith('<'):
        parts = [int(x, 16) for x in raw.split()]
        if len(parts) == 2 and u.normalize('NFC', chr(parts[0]) + chr(parts[1])) == c:
            comp.append((parts[0], parts[1], cp))
comp.sort()

def arr(name, vals, per=12):
    out = [f'static const uint32_t {name}[{len(vals)}] = {{']
    for i in range(0, len(vals), per):
        out.append('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    out.append('};')
    return out

lines = [f'/* Generated by tools/gen_norm.py from Python {sys.version.split()[0]} (Unicode {u.unidata_version}): the tables',
         '   for Unicode normalization. Characters not listed have combining class 0 and decompose to themselves. */']
lines += arr('vu_ccc_cp', [c for c, _ in ccc])
lines += [f'static const uint8_t vu_ccc_v[{len(ccc)}] = {{'] + ['    ' + ', '.join(str(v) for _, v in ccc[i:i + 24]) + ',' for i in range(0, len(ccc), 24)] + ['};']
for name, tab in (('nfd', nfd), ('nfkd', nfkd)):
    pool, at = [], []
    for cp, xs in tab:
        at.append(len(pool) << 5 | len(xs))
        pool += xs
    assert max(len(xs) for _, xs in tab) < 32
    lines += arr(f'vu_{name}_cp', [cp for cp, _ in tab])
    lines += arr(f'vu_{name}_at', at)
    lines += arr(f'vu_{name}_pool', pool)
lines += arr('vu_comp_a', [a for a, _, _ in comp])
lines += arr('vu_comp_b', [b for _, b, _ in comp])
lines += arr('vu_comp_c', [c for _, _, c in comp])
lines += [f'#define VU_NCCC {len(ccc)}', f'#define VU_NNFD {len(nfd)}', f'#define VU_NNFKD {len(nfkd)}', f'#define VU_NCOMP {len(comp)}']
# character classes, as Python's str methods test them (one bit each), in runs of equal flags
def flags(cp):
    c = chr(cp)
    f = 0
    if c.isalpha(): f |= 1
    if c.isdigit(): f |= 2
    if c.isspace(): f |= 4
    if c.isalnum(): f |= 8
    if c.isupper(): f |= 16
    if c.islower(): f |= 32
    if u.category(c) == 'Lt': f |= 64
    if c.isdecimal(): f |= 128
    return f
runs = []
prev = None
for cp in range(0, 0x110000):
    f = 0 if 0xD800 <= cp <= 0xDFFF else flags(cp)
    if f != prev:
        runs.append((cp, f))
        prev = f
lines += arr('vu_cls_start', [a for a, _ in runs])
lines += [f'static const uint8_t vu_cls_flag[{len(runs)}] = {{'] + ['    ' + ', '.join(str(v) for _, v in runs[i:i + 24]) + ',' for i in range(0, len(runs), 24)] + ['};']
lines.append(f'#define VU_NCLS {len(runs)}')
lines.append(r'''
static int vu_cls(uint32_t cp) {
    int64_t lo = 0, hi = VU_NCLS - 1;
    while (lo < hi) {
        int64_t m = (lo + hi + 1) / 2;
        if (vu_cls_start[m] <= cp) lo = m; else hi = m - 1;
    }
    return vu_cls_flag[lo];
}
/* s.is_alpha() and the rest, as Python's isalpha(), isdigit(), isspace(), isalnum(), isupper(),
   islower() and isdecimal(): false for "" and for bytes that aren't UTF-8. which: the flag bit;
   upper and lower are the cased tests (bit 16 / 32). */
static bool vu_str_is(const vu_str *s, int which) {
    const uint8_t *p = s->data;
    int64_t n = s->len, i = 0;
    if (n == 0) return false;
    bool cased = false;
    while (i < n) {
        int32_t cp;
        size_t len = vu_utf8_next(p + i, (size_t)(n - i), &cp);
        if (cp < 0) return false;
        i += (int64_t)len;
        int f = vu_cls((uint32_t)cp);
        if (which == 16) {
            if (f & (32 | 64)) return false;
            if (f & 16) cased = true;
        } else if (which == 32) {
            if (f & (16 | 64)) return false;
            if (f & 32) cased = true;
        } else if (!(f & which)) return false;
    }
    return (which == 16 || which == 32) ? cased : true;
}
static int64_t vu_norm_find(const uint32_t *a, int64_t n, uint32_t cp) {
    int64_t lo = 0, hi = n - 1;
    while (lo <= hi) {
        int64_t m = (lo + hi) / 2;
        if (a[m] == cp) return m;
        if (a[m] < cp) lo = m + 1; else hi = m - 1;
    }
    return -1;
}
static int vu_norm_ccc(uint32_t cp) {
    if (cp < 0x300) return 0;
    int64_t i = vu_norm_find(vu_ccc_cp, VU_NCCC, cp);
    return i < 0 ? 0 : vu_ccc_v[i];
}
/* the pair (a, b) composes to: 0 if it doesn't */
static uint32_t vu_norm_compose(uint32_t a, uint32_t b) {
    if (a >= 0x1100 && a < 0x1113 && b >= 0x1161 && b < 0x1176) return 0xAC00 + ((a - 0x1100) * 21 + (b - 0x1161)) * 28;
    if (a >= 0xAC00 && a <= 0xD7A3 && (a - 0xAC00) % 28 == 0 && b > 0x11A7 && b < 0x11C3) return a + (b - 0x11A7);
    int64_t lo = 0, hi = VU_NCOMP - 1;
    while (lo <= hi) {
        int64_t m = (lo + hi) / 2;
        if (vu_comp_a[m] == a && vu_comp_b[m] == b) return vu_comp_c[m];
        if (vu_comp_a[m] < a || (vu_comp_a[m] == a && vu_comp_b[m] < b)) lo = m + 1; else hi = m - 1;
    }
    return 0;
}
typedef struct { uint32_t *d; int64_t len, cap; } vu_cps;
static void vu_cps_push(vu_cps *c, uint32_t x) {
    if (c->len == c->cap) {
        c->cap = c->cap ? c->cap * 2 : 64;
        c->d = (uint32_t *)realloc(c->d, (size_t)c->cap * sizeof *c->d);
        if (!c->d) vu_oom();
    }
    c->d[c->len++] = x;
}
/* s.normalize(form): form is "NFC", "NFD", "NFKC" or "NFKD". Bytes that aren't UTF-8 stay as they are
   (each one a character of its own that nothing composes with). */
static vu_str vu_str_normalize(const vu_str *s, const vu_str *form, int line) {
    int kind = -1;   /* bit 1: compatibility; bit 0: compose */
    if (form->len == 3 && memcmp(form->data, "NFC", 3) == 0) kind = 1;
    else if (form->len == 3 && memcmp(form->data, "NFD", 3) == 0) kind = 0;
    else if (form->len == 4 && memcmp(form->data, "NFKC", 4) == 0) kind = 3;
    else if (form->len == 4 && memcmp(form->data, "NFKD", 4) == 0) kind = 2;
    else vu_fail(line, "normalize(): the form is \"NFC\", \"NFD\", \"NFKC\" or \"NFKD\"");
    const uint8_t *p = s->data;
    int64_t n = s->len, i = 0;
    while (i < n && p[i] < 0x80) i++;
    vu_str out = {0};
    if (i == n) { vu_str_cat_bytes(&out, p, n); return out; }   /* ASCII: every form is the same */
    /* decompose (marking bytes that aren't UTF-8 with bit 31) */
    vu_cps c = {0};
    const uint32_t *dcp = kind & 2 ? vu_nfkd_cp : vu_nfd_cp, *dat = kind & 2 ? vu_nfkd_at : vu_nfd_at, *dpool = kind & 2 ? vu_nfkd_pool : vu_nfd_pool;
    int64_t dn = kind & 2 ? VU_NNFKD : VU_NNFD;
    i = 0;
    while (i < n) {
        int32_t cp;
        size_t len = vu_utf8_next(p + i, (size_t)(n - i), &cp);
        if (cp < 0) { vu_cps_push(&c, 0x80000000u | p[i]); i++; continue; }
        i += (int64_t)len;
        uint32_t u = (uint32_t)cp;
        if (u >= 0xAC00 && u <= 0xD7A3) {
            uint32_t sidx = u - 0xAC00;
            vu_cps_push(&c, 0x1100 + sidx / 588);
            vu_cps_push(&c, 0x1161 + (sidx % 588) / 28);
            if (sidx % 28) vu_cps_push(&c, 0x11A7 + sidx % 28);
            continue;
        }
        int64_t k = u < 0xC0 && !(kind & 2) ? -1 : vu_norm_find(dcp, dn, u);
        if (k < 0) { vu_cps_push(&c, u); continue; }
        for (uint32_t j = 0; j < (dat[k] & 31); j++) vu_cps_push(&c, dpool[(dat[k] >> 5) + j]);
    }
    /* canonical order: a stable sort of each run of non-starters by combining class */
    for (int64_t a = 0; a < c.len;) {
        if ((c.d[a] & 0x80000000u) || vu_norm_ccc(c.d[a]) == 0) { a++; continue; }
        int64_t b = a;
        while (b < c.len && !(c.d[b] & 0x80000000u) && vu_norm_ccc(c.d[b]) != 0) b++;
        for (int64_t x = a + 1; x < b; x++) {
            uint32_t v = c.d[x];
            int cv = vu_norm_ccc(v);
            int64_t y = x;
            while (y > a && vu_norm_ccc(c.d[y - 1]) > cv) { c.d[y] = c.d[y - 1]; y--; }
            c.d[y] = v;
        }
        a = b;
    }
    if (kind & 1) {
        /* compose: each character with the last starter, unless something between blocks it */
        int64_t w = 0, starter = -1;
        int last_ccc = -1;
        for (int64_t r = 0; r < c.len; r++) {
            uint32_t v = c.d[r];
            int cv = (v & 0x80000000u) ? 0 : vu_norm_ccc(v);
            if (starter >= 0 && !(v & 0x80000000u) && !(c.d[starter] & 0x80000000u) && (last_ccc < cv || (last_ccc == 0 && w == starter + 1))) {
                uint32_t m = vu_norm_compose(c.d[starter], v);
                if (m) { c.d[starter] = m; continue; }
            }
            if (cv == 0) { starter = w; last_ccc = 0; }
            else last_ccc = cv;
            c.d[w++] = v;
            if (cv == 0) last_ccc = 0;
        }
        c.len = w;
    }
    for (int64_t k = 0; k < c.len; k++) {
        uint32_t v = c.d[k];
        if (v & 0x80000000u) { uint8_t b = (uint8_t)v; vu_str_cat_bytes(&out, &b, 1); continue; }
        uint8_t buf[4];
        int m;
        if (v < 0x80) { buf[0] = (uint8_t)v; m = 1; }
        else if (v < 0x800) { buf[0] = (uint8_t)(0xC0 | v >> 6); buf[1] = (uint8_t)(0x80 | (v & 63)); m = 2; }
        else if (v < 0x10000) { buf[0] = (uint8_t)(0xE0 | v >> 12); buf[1] = (uint8_t)(0x80 | (v >> 6 & 63)); buf[2] = (uint8_t)(0x80 | (v & 63)); m = 3; }
        else { buf[0] = (uint8_t)(0xF0 | v >> 18); buf[1] = (uint8_t)(0x80 | (v >> 12 & 63)); buf[2] = (uint8_t)(0x80 | (v >> 6 & 63)); buf[3] = (uint8_t)(0x80 | (v & 63)); m = 4; }
        vu_str_cat_bytes(&out, buf, m);
    }
    free(c.d);
    return out;
}''')
open('compiler/rt/norm.c', 'w').write('\n'.join(lines) + '\n')
print(len(ccc), len(nfd), len(nfkd), len(comp))
