"""Generates compiler/rt/case.c: the tables behind s.upper() and s.lower(), from Python's own
str.upper() and str.lower(), so Vu changes case exactly as Python does (one exception: Python's
lower() turns a word-final capital sigma into the final form; Vu always gives the ordinary sigma).
Run from the repository root:  python3 tools/gen_case.py   (the result is checked in)."""
import sys
import unicodedata

def table(name, conv):
    entries, pool = [], bytearray()
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        if conv == 'lower' and cp == 0x03A3:
            out = 'σ'          # (the context-free answer; see above)
        else:
            out = getattr(c, conv)()
        if out == c:
            continue
        b = out.encode('utf-8')
        entries.append((cp, len(pool), len(b)))
        pool += b
    lines = [f'static const uint32_t vu_{name}_cp[{len(entries)}] = {{']
    for i in range(0, len(entries), 12):
        lines.append('    ' + ', '.join(str(e[0]) for e in entries[i:i + 12]) + ',')
    lines.append('};')
    lines.append(f'static const uint32_t vu_{name}_at[{len(entries)}] = {{   /* offset << 8 | length, in vu_{name}_pool */')
    for i in range(0, len(entries), 12):
        lines.append('    ' + ', '.join(str(e[1] << 8 | e[2]) for e in entries[i:i + 12]) + ',')
    lines.append('};')
    lines.append(f'static const unsigned char vu_{name}_pool[{len(pool)}] = {{')
    for i in range(0, len(pool), 24):
        lines.append('    ' + ', '.join(str(x) for x in pool[i:i + 24]) + ',')
    lines.append('};')
    return '\n'.join(lines), len(entries)

up, nu = table('upper', 'upper')
lo, nl = table('lower', 'lower')
out = f'''/* Generated by tools/gen_case.py from Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}): the characters outside
   ASCII whose upper or lower case differs, sorted, with what each becomes (UTF-8, up to 3 characters). */
{up}
{lo}
#define VU_NUPPER {nu}
#define VU_NLOWER {nl}
/* s.upper() and s.lower(): ASCII directly, other characters through the tables; bytes that aren't
   UTF-8 are copied as they are. */
static vu_str vu_case(const vu_str *s, bool upper) {{
    const uint32_t *cps = upper ? vu_upper_cp : vu_lower_cp;
    const uint32_t *at = upper ? vu_upper_at : vu_lower_at;
    const unsigned char *pool = upper ? vu_upper_pool : vu_lower_pool;
    int64_t n = upper ? VU_NUPPER : VU_NLOWER;
    vu_str r = {{0}};
    vu_str_reserve(&r, s->len);
    const unsigned char *d = s->data;
    int64_t i = 0;
    while (i < s->len) {{
        unsigned char c = d[i];
        if (c < 0x80) {{
            if (upper && c >= 'a' && c <= 'z') c -= 32;
            else if (!upper && c >= 'A' && c <= 'Z') c += 32;
            vu_str_cat_bytes(&r, &c, 1);
            i++;
            continue;
        }}
        int32_t cp;
        size_t k = vu_utf8_next(d + i, (size_t)(s->len - i), &cp);
        int64_t lo = 0, hi = n - 1, found = -1;
        while (cp >= 0 && lo <= hi) {{
            int64_t mid = (lo + hi) / 2;
            if (cps[mid] == (uint32_t)cp) {{ found = mid; break; }}
            if (cps[mid] < (uint32_t)cp) lo = mid + 1; else hi = mid - 1;
        }}
        if (found >= 0) vu_str_cat_bytes(&r, pool + (at[found] >> 8), (int64_t)(at[found] & 255));
        else vu_str_cat_bytes(&r, d + i, (int64_t)k);
        i += (int64_t)k;
    }}
    return r;
}}
'''
open('compiler/rt/case.c', 'w').write(out)
print(f'upper {nu}, lower {nl}')
