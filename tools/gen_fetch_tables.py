#!/usr/bin/env python3
r"""Writes mcp/fetch/tables.vu: what the fetch server needs to read text as Python does.
  CODECS   every name Python's codecs.lookup() finds through the encodings package (a for an alias,
           m for a module name, as encodings.normalize_encoding leaves it): the codec's own name, its kind
           (B: decoded by charset.vu itself, T: a single-byte table below, U: a text codec charset.vu
           can't decode, N: not a text codec) and whether it reads ASCII as ASCII (1 or 0)
  BYTES    for each single-byte codec: its name, then the character of each byte from 0 to 255 in
           hex ("-" for a byte it can't decode)
  ENTITIES the HTML5 named character references (html.entities.html5): name, then the characters
  CHARREFS html.unescape's replacements for numeric references to some code points (hex, then the
           replacement's characters, "-" for none), and the code points it drops ("x" lines)
  tools/gen_fetch_tables.py"""
import codecs, encodings, html.entities, importlib, os, pkgutil, warnings
warnings.simplefilter("ignore")
from encodings.aliases import aliases

BUILTIN = {"ascii", "iso8859-1", "utf-8", "utf-8-sig", "utf-16", "utf-16-le", "utf-16-be", "utf-32", "utf-32-le", "utf-32-be"}
probe = b"\t\n\r" + bytes(range(0x20, 0x7F))
modules = {m.name for m in pkgutil.iter_modules(encodings.__path__)} - {"aliases", "charmap", "mbcs", "oem"}
names = set(aliases) | modules
rows, tables, seen = [], [], set()
for n in sorted(names):
    try: info = codecs.lookup(n)
    except LookupError: continue
    if getattr(info, "_is_text_encoding", True) is False:
        rows.append("%s %s %s N 0" % ("a" if n in aliases else "m", n, info.name)); continue
    try: compat = 1 if probe.decode(info.name) == probe.decode("ascii") else 0
    except Exception: compat = 0
    if info.name in BUILTIN: kind = "B"
    else:
        mod = importlib.import_module("encodings." + info.name.replace("-", "_")) if info.name.replace("-", "_") in {m.name for m in pkgutil.iter_modules(encodings.__path__)} else None
        table = getattr(mod, "decoding_table", None) if mod else None
        if table is None and mod is not None and hasattr(mod, "decoding_map"):
            dm = mod.decoding_map
            table = "".join(chr(dm[b]) if dm.get(b) is not None else "￾" for b in range(256))
        kind = "T" if table is not None else "U"
        if kind == "T" and info.name not in seen:
            seen.add(info.name)
            cells = []
            for b in range(256):
                try: cells.append("%X" % ord(bytes([b]).decode(info.name)))
                except UnicodeDecodeError: cells.append("-")
            tables.append(info.name + " " + " ".join(cells))
    rows.append("%s %s %s %s %d" % ("a" if n in aliases else "m", n, info.name, kind, compat))
ents = ["%s %s" % (k, "+".join("%X" % ord(c) for c in v)) for k, v in sorted(html.entities.html5.items())]
import html as _html
refs = ["%X %s" % (k, "+".join("%X" % ord(c) for c in v) or "-") for k, v in sorted(_html._invalid_charrefs.items())]
refs += ["%X x" % k for k in sorted(_html._invalid_codepoints)]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mcp", "fetch", "tables.vu")
with open(out, "w") as f:
    f.write("# Python's text codecs and HTML entities, for the fetch server. Generated by tools/gen_fetch_tables.py\n"
            "# (which says what each line holds).\n")
    for name, lines in (("CODECS", rows), ("BYTES", tables), ("ENTITIES", ents), ("CHARREFS", refs)):
        f.write('const %s = """\n%s\n"""\n' % (name, "\n".join(lines)))
print("%d names, %d tables, %d entities -> %s" % (len(rows), len(tables), len(ents), out))
