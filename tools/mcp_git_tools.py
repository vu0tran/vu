#!/usr/bin/env python3
"""Writes mcp/git/tools.vu: the reference git server's tool list, exactly as its
tools/list returns it, as a Vu text constant.
  tools/mcp_git_tools.py PYTHON     (a Python that has mcp-server-git, as tests/run_mcp_git.sh sets up)"""
import json, os, subprocess, sys
p = subprocess.Popen([sys.argv[1], "-m", "mcp_server_git"], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
msgs = [{"jsonrpc": "2.0", "id": 0, "method": "initialize", "params": {"protocolVersion": "2025-11-25", "capabilities": {}, "clientInfo": {"name": "gen", "version": "1"}}},
        {"jsonrpc": "2.0", "method": "notifications/initialized"},
        {"jsonrpc": "2.0", "id": 1, "method": "tools/list"}]
for m in msgs: p.stdin.write((json.dumps(m) + "\n").encode())
p.stdin.flush()
init = json.loads(p.stdout.readline())["result"]
tools = json.loads(p.stdout.readline())["result"]["tools"]
p.stdin.close(); p.wait()
def vu(v): return json.dumps(v, separators=(",", ":"), ensure_ascii=False).replace("\\", "\\\\").replace("{", "{{").replace("}", "}}")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mcp", "git", "tools.vu")
with open(out, "w") as f:
    f.write("# The tools, exactly as the reference server (mcp-server-git %s) lists them.\n"
            "# Generated by tools/mcp_git_tools.py.\n" % init["serverInfo"]["version"])
    f.write('const VERSION = "%s"\n' % init["serverInfo"]["version"])
    f.write('const TOOLS = """\n%s\n"""\n' % vu(tools))
print("%d tools -> %s" % (len(tools), out))
