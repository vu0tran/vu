#!/usr/bin/env python3
"""Writes mcp/sqlite/tools.vu: the reference SQLite server's tools, prompt, resource list, prompt text
and capabilities, exactly as it answers them, as Vu text constants.
  tools/mcp_sqlite_tools.py MCP_SERVER_SQLITE    (the reference's command, from a venv with mcp<2)"""
import json, os, subprocess, sys, tempfile
d = tempfile.mkdtemp()
p = subprocess.Popen([sys.argv[1], "--db-path", os.path.join(d, "x.db")], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
MARK = "@@TOPIC@@"
msgs = [{"jsonrpc": "2.0", "id": 0, "method": "initialize", "params": {"protocolVersion": "2025-11-25", "capabilities": {}, "clientInfo": {"name": "gen", "version": "1"}}},
        {"jsonrpc": "2.0", "method": "notifications/initialized"},
        {"jsonrpc": "2.0", "id": 1, "method": "tools/list"}, {"jsonrpc": "2.0", "id": 2, "method": "prompts/list"},
        {"jsonrpc": "2.0", "id": 3, "method": "resources/list"},
        {"jsonrpc": "2.0", "id": 4, "method": "prompts/get", "params": {"name": "mcp-demo", "arguments": {"topic": MARK}}}]
for m in msgs: p.stdin.write((json.dumps(m) + "\n").encode())
p.stdin.flush()
init = json.loads(p.stdout.readline())["result"]
tools = json.loads(p.stdout.readline())["result"]["tools"]
prompts = json.loads(p.stdout.readline())["result"]["prompts"]
res = json.loads(p.stdout.readline())["result"]["resources"]
text = json.loads(p.stdout.readline())["result"]["messages"][0]["content"]["text"]
p.stdin.close(); p.wait()
def vu(v): return json.dumps(v, separators=(",", ":"), ensure_ascii=False).replace("\\", "\\\\").replace("{", "{{").replace("}", "}}")
def vutext(t): return t.replace("\\", "\\\\").replace("{", "{{").replace("}", "}}").replace(MARK, "%TOPIC%")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mcp", "sqlite", "tools.vu")
with open(out, "w") as f:
    f.write("# What the reference SQLite server (mcp-server-sqlite 2025.4.25) lists and answers, exactly: its\n"
            "# tools, prompt, resource, the prompt's text (%TOPIC% for the topic) and its capabilities.\n"
            "# Generated by tools/mcp_sqlite_tools.py.\n")
    f.write('const NAME = "%s"\nconst VERSION = "%s"\n' % (init["serverInfo"]["name"], init["serverInfo"]["version"]))
    for k, v in (("CAPS", init["capabilities"]), ("TOOLS", tools), ("PROMPTS", prompts), ("RESOURCES", res)):
        f.write('const %s = """\n%s\n"""\n' % (k, vu(v)))
    f.write('const DEMO = """\n%s\n"""\n' % vutext(text))
print("%d tools -> %s" % (len(tools), out))
