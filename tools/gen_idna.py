#!/usr/bin/env python3
"""Writes mcp/fetch/idna_table.vu: how a URL's host treats each non-ASCII code point, as the reference
fetch server's URL check (pydantic's AnyUrl, the Rust url crate's UTS #46 processing) treats it,
found by asking it about every code point in the middle of a label ("http://q<c>q/": no letter
composes with q). One row per range: start and end (hex), and V (valid, kept), W (valid, a
combining mark, which can't start a label), X (an error), I (ignored: removed), M (mapped to
the code point at a constant distance, given in decimal) or S (mapped to the code points given in
hex, joined by +).
  tools/gen_idna.py     (run with a Python that has pydantic, as tests/run_mcp_fetch.sh sets up)"""
import os, unicodedata
from pydantic import TypeAdapter, AnyUrl, ValidationError
ta = TypeAdapter(AnyUrl)

def probe(c):
    ch = chr(c)
    try:
        h = str(ta.validate_python("http://q" + ch + "q/"))[7:-1]
    except ValidationError:
        return ("X", None)
    try:
        dec = ".".join(l[4:].encode().decode("punycode") if l.startswith("xn--") else l for l in h.split("."))
    except Exception:
        return ("X", None)
    m = dec[1:-1]
    if m == ch: return ("W" if unicodedata.category(ch).startswith("M") else "V", None)
    if m == "": return ("I", None)
    if len(m) == 1: return ("M", ord(m) - c)
    return ("S", "+".join("%X" % ord(x) for x in m))

rows = []
for c in range(0x80, 0x110000):
    if 0xD800 <= c < 0xE000: continue
    k, v = probe(c)
    if rows and rows[-1][2] == k and rows[-1][3] == v and rows[-1][1] == c - 1 and k != "S": rows[-1][1] = c
    elif rows and rows[-1][2] == k and k in "VWXI" and rows[-1][1] == 0xD7FF and c == 0xE000: rows[-1][1] = c
    else: rows.append([c, c, k, v])
lines = ["%X %X %s%s" % (a, b, k, "" if v is None else " %s" % v) for a, b, k, v in rows]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mcp", "fetch", "idna_table.vu")
with open(out, "w") as f:
    f.write("# How a URL's host treats each non-ASCII code point, as the reference server's URL check does.\n"
            "# Generated by tools/gen_idna.py: start end (hex), then V (kept), W (kept, a combining mark),\n"
            "# X (an error), I (removed),\n"
            "# M delta (mapped to the code point delta away) or S a+b (mapped to those code points).\n"
            'const IDNA = """\n%s\n"""\n' % "\n".join(lines))
print("%d ranges -> %s" % (len(rows), out))
