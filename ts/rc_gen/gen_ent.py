# Generates ts/rc_ent.vu from oxc_syntax/src/xml_entities.rs: the JSX entity table and decoding.
import re, sys
src = open(sys.argv[1]).read()
pairs = re.findall(r'"(\w+)" => \'(\\u\{([0-9A-Fa-f]+)\}|.)\'', src)
out = ['# Generated by rc_gen/gen_ent.py from oxc_syntax 1.90.0 xml_entities.rs: JSX character',
       '# references (&amp; &#123; &#x1F600;), decoded as oxc decodes them.', '',
       'import scan', '',
       'fn entity_table() -> {Str: Int}:',
       '  var m: {Str: Int} = {}']
for name, lit, hexv in pairs:
    cp = int(hexv, 16) if hexv else ord(lit)
    out.append('  m["%s"] = %d' % (name, cp))
out.append('  return m')
out.append('''
fn is_digit_radix(c: Byte, radix: Int) -> Bool:
  if c >= '0' and c <= '9': return true
  if radix == 16 and ((c >= 'a' and c <= 'f') or (c >= 'A' and c <= 'F')): return true
  return false

# decode_entity: the code point, or -1
fn decode_entity(tab: {Str: Int}, word: Str) -> Int:
  if word.len > 0 and word[0] == '#':
    var digits = word[1..word.len]
    var radix = 10
    if digits.len > 0 and digits[0] == 'x':
      digits = digits[1..digits.len]
      radix = 16
    if digits.len == 0: return -1
    var v = 0
    for i in 0..digits.len:
      if not is_digit_radix(digits[i], radix): return -1
      v = v * radix + scan.hexval(digits[i])
      if v > 1114111: return -1
    return v
  return tab.get(word, -1)

# decode_entities: unknown references are kept as written
fn decode_entities(tab: {Str: Int}, s: Str) -> Str:
  if s.find("&") < 0: return s
  var out = ""
  var prev = 0
  var i = 0
  while i < s.len:
    if s[i] != '&':
      i += 1
      continue
    var start = i
    var end = -1
    var j = i + 1
    while j < s.len:
      if s[j] == ';':
        end = j
        break
      if s[j] == '&': start = j
      j += 1
    if end < 0: break
    out = out + s[prev..start]
    prev = end + 1
    let word = s[start + 1..end]
    let cp = decode_entity(tab, word)
    if cp >= 0: out = out + scan.utf8(cp)
    else: out = out + "&" + word + ";"
    i = end + 1
  return out + s[prev..s.len]
''')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(pairs))
