#!/usr/bin/env python3
# Writes ts/ltslib.vu: TypeScript 7's lib files (lib.*.d.ts, Apache-2.0, Microsoft) as tsgolint
# bundles them, so vtsc type-checks with the libs oxlint's tsgolint uses, without TypeScript or
# tsgolint installed. vlint writes them once to its cache folder (lvtsc.bundled_lib).
#   python3 ts/tslib/gen_tslib.py TYPESCRIPT_GO/internal/bundled/libs
# (tsgolint v7.0.2005, what oxlint 1.90.0 requires, pins typescript-go 2bd066d8.)
import hashlib
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1]
names = sorted(n for n in os.listdir(src) if n.endswith(".d.ts"))
texts = []
h = hashlib.sha256()
for n in names:
    with open(os.path.join(src, n), encoding="utf8") as f:
        t = f.read()
    texts.append(t)
    h.update(n.encode() + b"\0" + t.encode("utf8") + b"\0")
digest = h.hexdigest()[:16]


def vu_str(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "{":
            out.append("{{")
        elif ch == "}":
            out.append("}}")
        elif ord(ch) < 32:
            out.append("\\u{%04x}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


with open(os.path.join(here, "..", "ltslib.vu"), "w", encoding="utf8") as f:
    f.write("# Generated by ts/tslib/gen_tslib.py: TypeScript 7's lib files as tsgolint bundles them\n")
    f.write("# (typescript-go, Apache License 2.0, Copyright (c) Microsoft Corporation; ts/tslib/LICENSE).\n")
    f.write("# Don't edit; regenerate.\n\n")
    f.write('const TSLIB_HASH = "%s"\n\n' % digest)
    f.write("fn names() -> [Str]:\n  return [" + ", ".join(vu_str(n) for n in names) + "]\n\n")
    f.write("fn text(i: Int) -> Str:\n")
    for i, t in enumerate(texts):
        f.write("  if i == %d: return %s\n" % (i, vu_str(t)))
    f.write('  return ""\n')
print(len(names), "lib files,", sum(len(t.encode()) for t in texts), "bytes, hash", digest)
