#!/usr/bin/env python3
# Generates limpl.vu: which of oxlint's rules (lmeta.vu) vlint implements, so a configuration that
# turns on one it doesn't is told so (on stderr) instead of the rule quietly reporting nothing.
# A rule counts as implemented when its diagnostic code ("plugin(rule)") appears in vlint's sources,
# when it's a jest rule reported through rjest's code(...) (jest and vitest both), or when it's
# type-aware (tsgolint or vtsc runs it). Run from ts/ after adding rules: python3 gen_impl.py
import re, glob

meta = []
for line in open('lmeta.vu'):
    m = re.match(r'^\s+(\d+) (\S+) (\S+) (\S+) (\S+) (\d) (\d) (\d) (\d)', line)
    if m: meta.append((int(m.group(1)), m.group(2), m.group(3), int(m.group(8))))
src = ''.join(open(f).read() for f in sorted(glob.glob('*.vu')) if f not in ('lmeta.vu', 'limpl.vu'))
codes = set(re.findall(r'"([a-z0-9_-]+)\(([A-Za-z0-9_-]+)\)', src))
for n in re.findall(r'code\([a-z0-9_.]*, "([a-z0-9-]+)"\)', open('rjest.vu').read()):
    codes.add(('jest', n)); codes.add(('vitest', n))
# (as lmeta's display_plugin prints them; react's two hooks rules print as react-hooks)
plugin_code = {'react_perf': 'react-perf', 'jsx_a11y': 'jsx-a11y', 'nextjs': 'next'}
def printed(p, r):
    out = [(plugin_code.get(p, p), r)]
    if p == 'react' and r in ('rules-of-hooks', 'exhaustive-deps'): out.append(('react-hooks', r))
    return out
ids = [i for i, p, r, ta in meta if ta or any(c in codes for c in printed(p, r))]
missing = len(meta) - len(ids)
with open('limpl.vu', 'w') as f:
    f.write('# Generated by gen_impl.py: the rules vlint implements (lmeta ids), {} of {} ({} not yet).\n\n'.format(len(ids), len(meta), missing))
    f.write('fn implemented(n: Int) -> [Bool]:\n  var b = [false] * n\n')
    for i in range(0, len(ids), 24):
        f.write('  for x in [{}]: b[x] = true\n'.format(', '.join(str(x) for x in ids[i:i + 24])))
    f.write('  return b\n')
print('limpl.vu: {} implemented, {} not'.format(len(ids), missing))
