# Extracts the Unicode data vjq's regex engine needs from Oniguruma 6.9.8's sources (BSD
# licensed, Copyright (c) 2002-2021 K.Kosako), the library jq 1.7.1 is built with:
# character properties (src/unicode_property_data.c) and simple case folding
# (src/unicode_fold_data.c). Writes jq/unitab.vu.
#   python3 gen_unicode.py JQ_SRC/modules/oniguruma/src > ../unitab.vu
import re, sys

d = sys.argv[1]
prop = open(d + "/unicode_property_data.c").read()

# code ranges, in CodeRanges[] order (that order is the ctype number)
ranges = {}
for m in re.finditer(r"^CR_(\w+)\[\] = \{ (\d+),(.*?)\}; /\* END of CR_\1 \*/", prop, re.M | re.S):
    nums = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]+)", m.group(3))]
    assert len(nums) == 2 * int(m.group(2)), m.group(1)
    ranges[m.group(1)] = nums
for a, b in re.findall(r"^#define CR_(\w+) CR_(\w+)$", prop, re.M):
    ranges[a] = ranges[b]
order = re.search(r"const CodeRanges\[\] = \{(.*?)\};", prop, re.S).group(1)
order = re.findall(r"CR_(\w+)", order)

# property names (lower case, no spaces, '-' or '_') to ctype
pool = dict(re.findall(r'char unicode_prop_name_pool_str(\d+)\[sizeof\("([^"]*)"\)\];', prop))
names = []
for m in re.finditer(r"\{pool_offset\((\d+)\),\s*(\d+)\}", prop):
    names.append((pool[m.group(1)], int(m.group(2))))

def enc(nums):
    # deltas in base 36: lo - previous hi, hi - lo
    out = []
    prev = 0
    for i in range(0, len(nums), 2):
        lo, hi = nums[i], nums[i + 1]
        out.append(b36(lo - prev) + "." + b36(hi - lo))
        prev = hi
    return ",".join(out)

def b36(n):
    s = ""
    while True:
        s = "0123456789abcdefghijklmnopqrstuvwxyz"[n % 36] + s
        n //= 36
        if n == 0: return s

fold = open(d + "/unicode_fold_data.c").read()
f1 = re.search(r"OnigUnicodeFolds1\[\] = \{(.*?)\};", fold, re.S).group(1)
f1 = f1.split("/* ----- LOCALE")[0]
f1 = re.sub(r"^#.*$", "", f1, flags=re.M)
f1 = re.sub(r"/\*.*?\*/", "", f1, flags=re.S)
f1 = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]+)", f1)] if False else [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", f1)]
pairs = []
i = 0
while i < len(f1):
    to, n = f1[i], f1[i + 1]
    for k in range(n):
        pairs.append((f1[i + 2 + k], to))
    i += 2 + n
pairs.sort()

out = ["# Generated by tools/gen_unicode.py from the Oniguruma jq 1.7.1 bundles (6.9.8, BSD licensed, Copyright (c)\n",
       "# 2002-2021 K.Kosako): Unicode properties and case folding for regex.vu. Do not edit.\n\n"]
out.append('const PROP_NAMES = "' + ",".join(f"{n}:{c}" for n, c in sorted(names)) + '"\n')
out.append('const PROP_RANGES = "' + ";".join(enc(ranges[n]) for n in order) + '"\n')
fl = []
prev = 0
for a, b in pairs:
    diff = b - a
    fl.append(b36(a - prev) + "." + ("-" + b36(-diff) if diff < 0 else b36(diff)))
    prev = a
out.append('const FOLDS = "' + ",".join(fl) + '"   # each: code point (delta from the last), its fold (delta from it)\n')
# multi-character folds (OnigUnicodeFolds2, OnigUnicodeFolds3): the folded sequence and the code
# points folding to it, in Oniguruma's order
for nm, k in (("OnigUnicodeFolds2", 2), ("OnigUnicodeFolds3", 3)):
    body = re.search(nm + r"\[\] = \{(.*?)\};", fold, re.S).group(1)
    body = body.split("/* ----- LOCALE")[0]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"^#.*$", "", body, flags=re.M)
    nums = [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", body)]
    ents = []
    i = 0
    while i < len(nums):
        t = nums[i:i + k]; n = nums[i + k]; us = nums[i + k + 1:i + k + 1 + n]
        i += k + 1 + n
        ents.append(" ".join("%x" % x for x in t) + ":" + " ".join("%x" % x for x in us))
    out.append("const FOLDS%d = \"" % k + ";".join(ents) + "\"\n")
sys.stdout.write("".join(out))
