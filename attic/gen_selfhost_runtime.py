#!/usr/bin/env python3
"""Generates compiler/runtime_gen.vu: the C runtime and code templates of vu.py as Vu functions, so the
self-hosted compiler emits exactly the same C. Run this after changing the runtime in vu.py."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
import vu  # noqa: E402


def lit(text):
    """A Vu string literal body for text (escapes, and {{ }} for literal braces)."""
    out = []
    for ch in text:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\t':
            out.append('\\t')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\0':
            out.append('\\0')
        elif ch == '{':
            out.append('{{')
        elif ch == '}':
            out.append('}}')
        elif ord(ch) < 32 or ord(ch) == 127:
            sys.exit(f'can\'t embed control character {ord(ch)}')
        else:
            out.append(ch)
    return ''.join(out)


def body(text, holes=()):
    """Vu statements appending text to `s`, one source line per statement; each (sentinel, name) in
    holes becomes an interpolation of that variable."""
    lines = text.split('\n')
    out = []
    for i, line in enumerate(lines):
        piece = line + ('\n' if i < len(lines) - 1 else '')
        if not piece:
            continue
        v = lit(piece)
        for sentinel, name in holes:
            v = v.replace(sentinel, '{' + name + '}')
        out.append(f'  s += "{v}"')
    return out


def fn(name, params, text, holes=()):
    lines = [f'fn {name}({params}) -> Str:', '  var s = ""']
    lines += body(text, holes)
    lines.append('  return s')
    return '\n'.join(lines)


class Stub:
    """Stands in for the code generator so map_c fills its template with sentinels."""
    def __init__(self, copy_val):
        self.copy_val = copy_val

    def mg(self, t):
        return '@@M@@'

    def ct(self, t):
        return '@@KC@@' if t in (vu.STR, ('keyx',)) else '@@VC@@'

    def is_copy(self, t):
        return self.copy_val

    def drop(self, t, lv):
        return f'drop_@@VM@@(&{lv});'


def main():
    parts = ['# ---- generated by tools/gen_selfhost_runtime.py from vu.py; do not edit by hand ----', '']
    parts.append(fn('rt_runtime', '', vu.RUNTIME))
    parts.append(fn('rt_float', '', vu.FLOAT_RT))
    parts.append(fn('rt_pow10', '', vu.POW10_TABLE))
    parts.append(fn('rt_tasks', '', vu.TASK_RT))
    parts.append(fn('rt_json', '', vu.JSON_RT))
    parts.append(fn('rt_ffi', '', vu.FFI_RT))
    parts.append(fn('rt_help', '', vu.__doc__.strip()))
    parts.append(fn('box_code', 'x: Str, t: Str', vu.box_code('@@X@@', '@@T@@'), [('@@X@@', 'x'), ('@@T@@', 't')]))
    parts.append(fn('list_code', 'm: Str, lt: Str, et: Str', vu.list_code('@@M@@', '@@L@@', '@@E@@'),
                    [('@@M@@', 'm'), ('@@L@@', 'lt'), ('@@E@@', 'et')]))
    holes = [('@@M@@', 'm'), ('@@KC@@', 'kc'), ('@@VC@@', 'vc'), ('@@VM@@', 'vm')]
    variants = []
    for str_key in (True, False):
        for copy_val in (True, False):
            key = vu.STR if str_key else ('keyx',)
            text = vu.Gen.map_c(Stub(copy_val), ('map', key, ('valx',)))
            name = f'map_code_{"s" if str_key else "i"}{"c" if copy_val else "o"}'
            variants.append((str_key, copy_val, name))
            parts.append(fn(name, 'm: Str, kc: Str, vc: Str, vm: Str', text, holes))
    disp = ['fn map_code(m: Str, kc: Str, vc: Str, vm: Str, str_key: Bool, copy_val: Bool) -> Str:']
    for str_key, copy_val, name in variants:
        cond = f'{"" if str_key else "not "}str_key and {"" if copy_val else "not "}copy_val'
        disp.append(f'  if {cond}: return {name}(m, kc, vc, vm)')
    disp.append('  return ""')
    parts.append('\n'.join(disp))
    out = os.path.join(HERE, '..', 'compiler', 'runtime_gen.vu')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w') as f:
        f.write('\n\n'.join(parts) + '\n')
    print(f'wrote {out}')


if __name__ == '__main__':
    main()
