#!/usr/bin/env python3
# Writes golint/misspell_data.vu from github.com/golangci/misspell v0.7.0's word lists
# (words.go, words_us.go, words_uk.go): one "typo<TAB>correction" pair per line, in the lists' order.
# usage: gen_misspell.py MISSPELL_DIR OUT.vu
import re, sys
d, outp = sys.argv[1:3]
def pairs(path, var):
    s = open(path).read()
    i = s.index("var " + var)
    body = s[i:s.index("\n}", i)]
    items = re.findall(r'"((?:[^"\\]|\\.)*)"', body)
    return [(items[k], items[k + 1]) for k in range(0, len(items) - 1, 2)]
out = ["# The misspell word lists (github.com/golangci/misspell v0.7.0), generated by tools/gen_misspell.py.", ""]
for name, path, var in (("main", "words.go", "DictMain"), ("us", "words_us.go", "DictAmerican"), ("uk", "words_uk.go", "DictBritish")):
    ps = pairs(d + "/" + path, var)
    for a, b in ps:
        assert "\t" not in a + b and "{" not in a + b and "\\" not in a + b and '"' not in a + b, (a, b)
    out.append("fn dict_%s() -> Str:" % name)
    out.append('  return "' + "\\n".join(a + "\\t" + b for a, b in ps) + '"')
    out.append("")
open(outp, "w").write("\n".join(out))
