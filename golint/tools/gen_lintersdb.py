#!/usr/bin/env python3
# Writes golint/lintersdb.vu from golangci-lint 2.5.0's own listings:
#   golangci-lint help linters --color never > help_linters.txt
#   golangci-lint help formatters --color never > help_formatters.txt
#   golangci-lint run --output.json.path json.txt ...   (its Report.Linters gives the registry order)
# usage: gen_lintersdb.py help_linters.txt help_formatters.txt json.txt OUT.vu
import json, sys
hl, hf, js, outp = sys.argv[1:5]
names = [l['Name'] for l in json.load(open(js))['Report']['Linters']]
def q(s): return s.replace('\\', '\\\\').replace('"', '\\"').replace('{', '{{').replace('}', '}}')
lines = [l.rstrip('\n') for l in open(hl)]
fl = [l.rstrip('\n') for l in open(hf)]
out = ["# The linters golangci-lint 2.5.0 knows (from `golangci-lint help linters`, and the JSON report's",
       "# order), generated by tools/gen_lintersdb.py.", ""]
out.append('const REG_ORDER = "' + " ".join(names) + '"')
out += ["", "fn help_lines() -> [Str]:", "  return [" + ", ".join('"%s"' % q(l) for l in lines) + "]", ""]
out += ["fn formatter_lines() -> [Str]:", "  return [" + ", ".join('"%s"' % q(l) for l in fl) + "]"]
open(outp, "w").write("\n".join(out) + "\n")
