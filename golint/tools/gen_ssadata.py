#!/usr/bin/env python3
# ssadata.vu from dumpfacts' output on the standard library (tools/dumpfacts/main.go, built inside a
# copy of honnef.co/go/tools v0.6.1 as cmd/dumpfacts, since it imports the internal buildir pass;
# run as `dumpfacts PKG...` over `go list std` in chunks): the exported functions and methods
# staticcheck's IR marks as never returning, and the ones its purity analysis marks pure.
import sys, re
noret, pure = set(), set()
for l in open(sys.argv[1]):
    p = l.split()
    if not p: continue
    name = p[-1]
    if "_test" in name or "internal/" in name or name.startswith("internal") or "vendor/" in name: continue
    last = re.split(r"[.)]", name)[-1]
    if not last[:1].isupper(): continue
    (noret if p[0] == "N" else pure).add(name)
out = sys.argv[2]
with open(out, "w") as f:
    f.write("# staticcheck v0.6.1's facts about the standard library (go1.24), generated by\n")
    f.write("# tools/gen_ssadata.py: exported functions that never return, and the pure ones.\n\n")
    for fn, s in (("std_noreturn", noret), ("std_pure", pure)):
        f.write("fn " + fn + "() -> {Str: Bool}:\n  var m: {Str: Bool} = {}\n")
        f.write('  for x in "' + " ".join(sorted(s)) + '".split(" "): m[x] = true\n  return m\n\n')
print(len(noret), len(pure))
