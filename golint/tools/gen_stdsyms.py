#!/usr/bin/env python3
# stdsyms.vu from golang.org/x/tools v0.50.0's internal/stdlib/manifest.go (the table goimports'
# fix.go reads as stdlib.PackageSymbols): each standard library package and the names of its
# exported constants, variables, types and functions (symbolNameSet's kinds; methods and fields left
# out). Usage: gen_stdsyms.py MANIFEST.go OUT.vu
import re, sys
cur, pk = None, {}
for line in open(sys.argv[1]):
    m = re.match(r'\t"([^"]+)": \{', line)
    if m:
        cur = m.group(1)
        pk[cur] = []
        continue
    m = re.match(r'\t\t\{"([^"]+)", (\w+),', line)
    if m and cur is not None and m.group(2) in ("Const", "Var", "Type", "Func"):
        pk[cur].append(m.group(1))
with open(sys.argv[2], "w") as f:
    f.write("# The standard library's exported names as goimports knows them (golang.org/x/tools v0.50.0,\n")
    f.write("# internal/stdlib's manifest: constants, variables, types and functions), generated by\n")
    f.write("# tools/gen_stdsyms.py. One line a package: its path, a tab, the names separated by spaces.\n\n")
    f.write("fn text() -> Str:\n  return \"")
    for p in sorted(pk):
        f.write(p + "\\t" + " ".join(pk[p]) + "\\n")
    f.write("\"\n")
