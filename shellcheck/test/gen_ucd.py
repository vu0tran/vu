w('')
w('# simple mappings: code point (6 hex digits), mapped (6)')
w(f'const NUP = {len(up)}')
w('const UPS = ' + ' + '.join('"' + p + '"' for p in chunks(''.join('%06X%06X' % (c, up[c]) for c in sorted(up)))))
w(f'const NLO = {len(lo)}')
w('const LOS = ' + ' + '.join('"' + p + '"' for p in chunks(''.join('%06X%06X' % (c, lo[c]) for c in sorted(lo)))))
