# gen_ucd.py UnicodeData.txt > ucd.vu: GHC 9.8's Data.Char (Unicode 15.1.0) for vsc: general
# categories as ranges and the simple case mappings, as hex strings searched in place.
import sys
CATS = ['Lu', 'Ll', 'Lt', 'Lm', 'Lo', 'Mn', 'Mc', 'Me', 'Nd', 'Nl', 'No', 'Pc', 'Pd', 'Ps', 'Pe', 'Pi', 'Pf', 'Po',
        'Sm', 'Sc', 'Sk', 'So', 'Zs', 'Zl', 'Zp', 'Cc', 'Cf', 'Cs', 'Co', 'Cn']
cat = {}
up, lo = {}, {}
first = None
for line in open(sys.argv[1]):
    f = line.rstrip('\n').split(';')
    c = int(f[0], 16)
    if f[1].endswith(', First>'):
        first = c
        continue
    if f[1].endswith(', Last>'):
        for x in range(first, c + 1): cat[x] = f[2]
        continue
    cat[c] = f[2]
    if f[12]: up[c] = int(f[12], 16)
    if f[13]: lo[c] = int(f[13], 16)
ranges = []
for c in range(0x110000):
    k = CATS.index(cat.get(c, 'Cn'))
    if ranges and ranges[-1][2] == k and ranges[-1][1] == c - 1: ranges[-1][1] = c
    else: ranges.append([c, c, k])
def chunks(s, n=96):
    return [s[i:i + n] for i in range(0, len(s), n)]
out = []
w = out.append
w('# GHC 9.8\'s Data.Char for vsc (Unicode 15.1.0): general categories and simple case mappings.')
w('# Generated by test/gen_ucd.py from UnicodeData.txt; do not edit.')
w('')
w('import astlib')
w('')
for name, val in [('CAT_LU', 0), ('CAT_LL', 1), ('CAT_LT', 2), ('CAT_LM', 3), ('CAT_LO', 4), ('CAT_ND', 8), ('CAT_NL', 9), ('CAT_NO', 10),
                  ('CAT_ZS', 22), ('CAT_ZL', 23), ('CAT_ZP', 24), ('CAT_CC', 25), ('CAT_CF', 26), ('CAT_CS', 27), ('CAT_CO', 28), ('CAT_CN', 29)]:
    w(f'const {name} = {val}')
w('')
w(f'# category ranges: start (6 hex digits), end (6), category (2)')
w(f'const NCAT = {len(ranges)}')
